// Slides 7 e 8 - Exportação NOMEADA com ES Modules (export function)
export function somar(a, b) {    // 'export' na frente já exporta a função com o nome exato 'somar'
  return a + b;                  // Devolve a soma de a + b
}                                // Fecha a função somar

export function dobrar(n) {      // 'export' na frente já exporta a função com o nome exato 'dobrar'
  return n * 2;                  // Devolve o dobro de n
}                                // Fecha a função dobrar

